"""Callbacks that collect generated media in the ADK session state."""

from __future__ import annotations

import logging

from google.adk.agents.callback_context import CallbackContext

from agent.utility.post_content import parse_post_content

logger = logging.getLogger(__name__)


def save_to_file(callback_context: CallbackContext) -> None:
    """Validate the latest graphic and append it once to ``generated_media``.

    The legacy name is kept because it is referenced by the agent definition;
    the callback persists media to session state rather than to a local file.
    """
    post_content = parse_post_content(callback_context.state.get("post_content"))
    if not post_content:
        logger.warning("Skipping invalid post_content generated by SVG agent")
        return

    serialized_content = post_content.model_dump()
    callback_context.state["post_content"] = serialized_content

    generated_media = list(callback_context.state.get("generated_media") or [])
    if any(
        (existing := parse_post_content(item))
        and existing.svg_code == post_content.svg_code
        for item in generated_media
    ):
        return

    generated_media.append(serialized_content)
    callback_context.state["generated_media"] = generated_media
